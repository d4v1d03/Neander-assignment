def test_the_public_contract_has_no_code_and_no_rule_details(database):
    deploy(database, APPS / "hiring")
    with app_server(database, "hiring") as port:
        status, _, body = get(port, "/_neai/contract")
    contract = json.loads(body)
    assert status == 200 and contract["app"] == "hiring" and contract["auth"]["roles"] == ["recruiter", "interviewer"]
    handlers = {x["name"]: x for x in contract["handlers"]}
    assert handlers["list_jobs"]["access"] == "public" and handlers["pass_round"]["access"] == ["recruiter", "interviewer"]
    steps = contract["workflows"]["hiring"]["steps"]
    assert steps[2] == {"name": "technical", "by": ["interviewer"]}  # who passes it, but not the skip rule
    text = body.decode()
    assert "skip_if" not in text and "prepare_offer" not in text and "def " not in text and "SALARY" not in text


def test_a_new_ui_goes_live_without_a_restart_and_rolls_back_with_its_version(database, tmp_path):
    src = ui_app(tmp_path, {"ui/index.html": "<p>v1</p>"})
    deploy(database, src)
    with app_server(database, "shop") as port:
        assert get(port, "/")[2] == b"<p>v1</p>"
        (src / "ui" / "index.html").write_text("<p>v2</p>")
        assert deploy(database, src)["version"] == 2
        assert get(port, "/")[2] == b"<p>v2</p>"
        rollback(database, "shop", 1)
        assert get(port, "/")[2] == b"<p>v1</p>"


@pytest.mark.parametrize("files,needle", [
    ({"ui/app.js": "x"}, "no index.html"),
    ({"ui/index.html": "x", "ui/logo.png": "x"}, "'.png' files"),
    ({"ui/index.html": "x", "ui/my page.html": "x"}, "names may use"),
])
def test_ui_folders_are_checked(database, tmp_path, files, needle):
    result = deploy(database, ui_app(tmp_path, files))
    assert result["error"]["code"] == "UI_INVALID" and needle in result["error"]["message"]


def test_hidden_files_are_ignored_and_symlinks_refused(database, tmp_path):
    src = ui_app(tmp_path, {"ui/index.html": "x", "ui/.DS_Store": "junk"})
    assert deploy(database, src)["status"] == "activated"
    os.symlink(src / "handlers.py", src / "ui" / "code.js")
    result = deploy(database, src)
    assert result["error"]["code"] == "UI_INVALID" and "symlink" in result["error"]["message"]


def test_deploy_warns_when_the_ui_calls_a_handler_that_doesnt_exist(database, tmp_path):
    src = ui_app(tmp_path, {"ui/index.html": "<script>neai.call('list_items'); neai.call(\"buy_item\", {})</script>"})
    warnings = deploy(database, src)["warnings"]
    assert warnings == ["ui/index.html calls neai.call('buy_item'), but app.json has no handler 'buy_item'"]


def test_the_shipped_apps_uis_only_call_real_handlers(database):
    assert deploy(database, APPS / "hiring")["warnings"] == []
