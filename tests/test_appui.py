from conftest import APPS


@contextmanager
def app_server(database, name):
    rt = Runtime(database, name)
    httpd = AppServer(0, rt, quiet=True)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    try:
        yield httpd.server_address[1]
    finally:
        httpd.shutdown()
        httpd.server_close()
        rt.close()


def get(port, path, host=None):
    conn = http.client.HTTPConnection("127.0.0.1", port, timeout=10)
    conn.request("GET", path, headers={"Host": host} if host else {})
    resp = conn.getresponse()
    return resp.status, dict(resp.getheaders()), resp.read()


def ui_app(tmp_path, files, name="shop"):
    src = tmp_path / name
    (src / "ui").mkdir(parents=True)
    (src / "app.json").write_text(json.dumps({"name": name, "collections": {"items": {"text": {"type": "string"}}},
                                              "handlers": {"list_items": {"kind": "read", "access": "public"}}}))
    (src / "handlers.py").write_text("def list_items(ctx, args):\n    return ctx.db.find('items')\n")
    for rel, text in files.items():
        (src / rel).parent.mkdir(parents=True, exist_ok=True)
        (src / rel).write_text(text)
    return src


def test_the_apps_own_ui_is_served_with_a_strict_policy(database, tmp_path):
    src = ui_app(tmp_path, {"ui/index.html": "<h1>Shop</h1><script src='/app.js'></script>",
                            "ui/app.js": "neai.call('list_items')", "ui/css/site.css": "h1 { color: red }"})
    assert deploy(database, src)["status"] == "activated"
    with app_server(database, "shop") as port:
        status, headers, body = get(port, "/")
        assert (status, body) == (200, b"<h1>Shop</h1><script src='/app.js'></script>")
        assert headers["Content-Type"] == "text/html; charset=utf-8"
        csp = headers["Content-Security-Policy"]
        assert "connect-src 'self'" in csp and "frame-ancestors 'none'" in csp and "object-src 'none'" in csp
        assert get(port, "/app.js")[1]["Content-Type"] == "text/javascript; charset=utf-8"
        assert get(port, "/css/site.css")[2] == b"h1 { color: red }"
        status, _, body = get(port, "/missing.js")
        assert status == 404 and json.loads(body)["error"]["code"] == "ROUTE_NOT_FOUND"
        for sneaky in ("/../app.json", "/%2e%2e/app.json", "/../handlers.py", "//etc/passwd"):
            assert get(port, sneaky)[0] == 404, sneaky
        assert get(port, "/", host="evil.example")[0] == 403
        status, headers, body = get(port, "/_neai/sdk.js")
        assert status == 200 and b"window.neai" in body and headers["Content-Type"].startswith("text/javascript")
        assert b"Generated by neai" in get(port, "/_neai/ui")[2]


